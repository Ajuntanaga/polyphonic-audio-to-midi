#!/usr/bin/env python3
"""Quantize a closed spectral-template TSV into a deterministic C++ include."""

from __future__ import annotations

import argparse
import csv
import pathlib


PHASES = {"corridor": 0, "onset": 1, "settled": 2}
FEATURES = 102


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()

    rows: list[tuple[int, int, int, list[int]]] = []
    indexes = [-1] * (3 * 128 * 8)
    with args.input.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream, delimiter="\t")
        if reader.fieldnames != ["phase", "midi_note", "string_index", "fingerprint"]:
            raise ValueError("unexpected template header")
        for record in reader:
            phase = PHASES[record["phase"]]
            note = int(record["midi_note"])
            string = int(record["string_index"])
            values = [float(value) for value in record["fingerprint"].split(",")]
            if len(values) != FEATURES or not 0 <= note < 128 or not 0 <= string < 8:
                raise ValueError("invalid template row")
            key = (phase * 128 + note) * 8 + string
            if indexes[key] >= 0:
                raise ValueError("duplicate template row")
            quantized = [round(max(0.0, min(1.0, value)) * 65535.0) for value in values]
            indexes[key] = len(rows)
            rows.append((phase, note, string, quantized))

    lines = [
        "// Generated by tools/generate_unison_spectral_templates.py; do not edit.",
        f"inline constexpr std::array<FactorySpectralRow, {len(rows)}U> kFactorySpectralRows{{{{",
    ]
    for phase, note, string, values in rows:
        packed = ",".join(str(value) for value in values)
        lines.append(
            f"  FactorySpectralRow{{{phase}U,{note}U,{string}U,{{{{{packed}}}}}}},"
        )
    lines.append("}};")
    lines.append(
        f"inline constexpr std::array<std::int16_t, {len(indexes)}U> kFactorySpectralIndex{{{{"
    )
    for offset in range(0, len(indexes), 32):
        lines.append("  " + ",".join(str(value) for value in indexes[offset:offset + 32]) + ",")
    lines.extend(("}};", ""))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
